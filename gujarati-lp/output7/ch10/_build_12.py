def words(s):
    return len([t for t in re.split(r"\s+", s.strip()) if re.search(r"[઀-૿]", t)])


def validate(out):
    errs = []
    src = json.load(open(os.path.join(HERE, "05_with_content.json"), encoding="utf-8"))
    ids, cids = [], {}
    for mod in src["modules"]:
        for seg in mod["segments"]:
            for t in seg["topics"]:
                ids.append(t["topic_id"])
                cids[t["topic_id"]] = [c["concept_id"] for c in t["concepts"]]
    if [t["topic_id"] for t in out["topics"]] != ids:
        errs.append("topic id set/order mismatch vs 05_with_content.json")
    for t in out["topics"]:
        tid = t["topic_id"]
        if [c["concept_id"] for c in t["concepts"]] != cids[tid]:
            errs.append("%s concept ids mismatch" % tid)
        for f in ("explanation", "real_life_example"):
            w = words(t[f])
            if not (55 <= w <= 90):
                errs.append("%s %s out of band: %d words" % (tid, f, w))
        if not (words(t["brief_summary"]) < words(t["summary"]) < words(t["detailed_summary"])):
            errs.append("%s summaries not strictly increasing" % tid)
        if not (3 <= len(t["concept_bullets"]) <= 4) or not (3 <= len(t["important_points"]) <= 4):
            errs.append("%s bullets out of band" % tid)
        if not (2 <= len(t["recall_questions"]) <= 3):
            errs.append("%s recall count out of band" % tid)
        for i, q in enumerate(t["recall_questions"], 1):
            if q["id"] != "%s.RQ%d" % (tid, i) or q["legacy_id"] != "%s.TR%d" % (tid, i):
                errs.append("%s recall id grammar" % tid)
            if q["bloom_level"] != q["bloom_level"].lower() or not q["answer"].strip():
                errs.append("%s recall bloom/answer" % tid)
        if not (3 <= len(t["shabdarth"]) <= 5):
            errs.append("%s shabdarth out of std-7 cap" % tid)
        if not (1 <= len(t["samanarthi"]) <= 2):
            errs.append("%s samanarthi out of std-7 cap" % tid)
        if len(t["vilom"]) > 1:
            errs.append("%s vilom out of std-7 cap" % tid)
        if len(t["vyakaran"]) != 1:
            errs.append("%s vyakaran must be 1 at std 7" % tid)
        if t["figures_of_speech"] != [] or t["rhyme_scheme"] is not None:
            errs.append("%s craft fields must be [] / null for ગદ્ય at std 7" % tid)
        if not isinstance(t["estimated_exchanges"], str):
            errs.append("%s estimated_exchanges not a string" % tid)
        for c in t["concepts"]:
            if not c["content"]:
                errs.append("%s %s empty content" % (tid, c["concept_id"]))
    for m in out["modules"]:
        if not (5 <= len(m["difficult_words"]) <= 10):
            errs.append("%s difficult_words out of band" % m["module_id"])
    # script and display-text gates
    def strings(o, path=""):
        if isinstance(o, dict):
            for k, v in o.items():
                yield from strings(v, path + "/" + str(k))
        elif isinstance(o, list):
            for i, v in enumerate(o):
                yield from strings(v, path + "/%d" % i)
        elif isinstance(o, str):
            yield path, o
    SKIP = ("concept_id", "topic_id", "module_id", "/id", "legacy_id", "/type", "difficulty",
            "bloom_level", "estimated_exchanges", "chapter_id", "plan_id", "agent", "notes")
    for path, s in strings(out):
        if any(k in path for k in SKIP):
            continue
        if re.search(r"[ऀ-ॿ]", s):
            errs.append("Devanagari in %s" % path)
        if "।" in s:
            errs.append("danda in %s" % path)
        if re.search(r"[0-9૦-૯]", s):
            errs.append("digit in display text %s" % path)
        if re.search(r"[A-Za-z]", s):
            errs.append("roman letter in %s" % path)
    return errs


