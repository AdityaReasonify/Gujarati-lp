# ---- checks ----
def words(s): return len([w for w in s.split() if w.strip()])
print("word counts publication_text vs teaching explanation:")
for t, o in zip(tw['topics'], out_topics):
    print(" ", t['topic_id'], words(o['publication_text']), "vs", words(t['explanation']))

bad = []
for o in out_topics:
    for field, s in [("publication_text", o['publication_text']), ("publication_chunk", o['publication_chunk'])] + \
                    [("cp:"+c['concept_id'], c['publication_text']) for c in o['concept_publication']]:
        for ch in s:
            cp = ord(ch)
            if 0x900 <= cp <= 0x97F: bad.append((o['topic_id'], field, 'devanagari', ch))
            if ch == '।': bad.append((o['topic_id'], field, 'danda', ch))
            if ('a' <= ch <= 'z') or ('A' <= ch <= 'Z'): bad.append((o['topic_id'], field, 'roman', ch))
            if ch.isdigit(): bad.append((o['topic_id'], field, 'digit', ch))
print("script/punct violations:", bad)

