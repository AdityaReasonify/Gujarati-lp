out_topics = []
for t in tw['topics']:
    tid = t['topic_id']
    ptext = EXPL[tid]
    pchunk = chunks[tid] + "\n\n" + ptext + "\n\n" + ANCHOR[tid]
    cps = []
    for c in t['concepts']:
        for i, b in enumerate(c['content']):
            if b.get('type') != 'paragraph':
                continue
            txt = CONCEPT_OVERRIDE.get((c['concept_id'], i), b['text'])
            cps.append({"concept_id": c['concept_id'], "content_index": i, "publication_text": txt})
    out_topics.append({"topic_id": tid, "publication_text": ptext,
                       "publication_chunk": pchunk, "concept_publication": cps})

